/**
 * 构建标记：一个能从**已发布产物**里直接读出来的版本号。
 *
 * 为什么需要它：今天为了确认「线上到底跑的是哪一版代码」，反复出过判断错误。
 * 从外部只能看到压缩后的 JS，只好拿某段代码「在不在」去反推版本——而
 * 「不在」既可能是**太旧还没加**，也可能是**够新已删掉**，两头都通，于是推错了两轮。
 *
 * 一个单调递增、且**只增不删**的字面量就没有这个歧义：
 *
 *   curl -s https://<站点>/ | grep -oE '/assets/index-[^"]*\.js' \
 *     | xargs -I{} curl -s https://<站点>{} | grep -o 'veil-build:[0-9-]*'
 *
 * 拿到的就是线上那一版。不需要登录，也不需要猜。
 *
 * 顺带：它还让 Lovable 的「有改动待发布」标记得以置位——从 GitHub 同步进来的提交
 * 不会自动把站点标记成待发布，而带上这个标记的提交会。
 */
export const BUILD_STAMP = 'veil-build:2026-09-02-1';

/**
 * 启动时打一行。console 调用不会被摇树掉，字面量因此必定留在产物里；
 * 同时开发者工具里也能一眼看到当前页面加载的是哪一版——
 * 单页应用只在加载那一刻取一次代码，标签页开着不刷新就永远是旧的那一版。
 */
export function logBuildStamp(): void {
  console.info(`[无知之幕] ${BUILD_STAMP}`);
}
